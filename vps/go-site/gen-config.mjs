#!/usr/bin/env node
/**
 * Writes vps/go-site/public/config.js (window.GO_CONFIG) for ONE environment from
 * an env file — the go.almahajja.app page calls get_live_by_code with it.
 *
 *   node vps/go-site/gen-config.mjs --env .env                 # production (go.almahajja.app)
 *   node vps/go-site/gen-config.mjs --env .env.staging.local   # staging
 *        [--out vps/go-site/public/config.js] [--app-store-url https://apps.apple.com/app/id…]
 *
 * Reads EXPO_PUBLIC_SUPABASE_URL + EXPO_PUBLIC_SUPABASE_ANON_KEY (the same public
 * client key the app ships) and, optionally, GO_APP_STORE_URL. Refuses anything
 * that looks like a service-role / secret key. Prints only the project ref — never
 * the key. Then copy the file to /opt/almahajja-go/public/config.js on the VPS
 * (no container restart needed; nginx serves it with Cache-Control: no-cache).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

function arg(name) {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : undefined;
}

function fail(msg) {
  console.error(`gen-config: ${msg}`);
  process.exit(1);
}

function loadEnv(path) {
  const out = {};
  let raw;
  try {
    raw = readFileSync(path, 'utf8');
  } catch {
    fail(`cannot read ${path}`);
  }
  for (const line of raw.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (!m) continue;
    out[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  return out;
}

/** The JWT `role` claim, or null for a non-JWT key. */
function jwtRole(key) {
  const parts = key.split('.');
  if (parts.length !== 3) return null;
  try {
    const json = JSON.parse(Buffer.from(parts[1].replace(/-/g, '+').replace(/_/g, '/'), 'base64').toString('utf8'));
    return typeof json.role === 'string' ? json.role : null;
  } catch {
    return null;
  }
}

const envPath = arg('env');
if (!envPath) fail('usage: node vps/go-site/gen-config.mjs --env <.env file> [--out <file>] [--app-store-url <url>]');
const env = { ...loadEnv(resolve(envPath)) };

const url = (env.EXPO_PUBLIC_SUPABASE_URL ?? '').replace(/\/+$/, '');
const key = env.EXPO_PUBLIC_SUPABASE_ANON_KEY ?? '';
const appStoreUrl = arg('app-store-url') ?? env.GO_APP_STORE_URL ?? '';

const ref = /^https:\/\/([a-z0-9]{20})\.supabase\.co$/.exec(url)?.[1];
if (!ref) fail('EXPO_PUBLIC_SUPABASE_URL must look like https://<ref>.supabase.co');
if (!key) fail('EXPO_PUBLIC_SUPABASE_ANON_KEY is missing');
if (key.startsWith('sb_secret_') || jwtRole(key) === 'service_role') {
  fail('refusing a service-role / secret key — config.js is public');
}
if (!(key.startsWith('sb_publishable_') || jwtRole(key) === 'anon')) {
  fail('EXPO_PUBLIC_SUPABASE_ANON_KEY is neither an anon JWT nor an sb_publishable_ key');
}
if (appStoreUrl && !/^https:\/\/apps\.apple\.com\//.test(appStoreUrl)) {
  fail('--app-store-url / GO_APP_STORE_URL must start with https://apps.apple.com/');
}

const envName = ref === 'prpyxnxgkpspjoxvcaro' ? 'prd' : 'stg';
const body =
  `// GENERATED by vps/go-site/gen-config.mjs — ${envName}. Do not edit, do not commit.\n` +
  `window.GO_CONFIG = ${JSON.stringify({ env: envName, supabaseUrl: url, anonKey: key, appStoreUrl }, null, 2)};\n`;

const out = resolve(arg('out') ?? join(here, 'public', 'config.js'));
writeFileSync(out, body, 'utf8');
console.log(`gen-config: wrote ${out} for ${envName} (${ref}); anon key not shown.`);
