#!/usr/bin/env node
// Copies the shared lecture-key naming module from the Supabase edge functions
// into this package, so the worker names server-transcoded lectures exactly
// like `r2-upload-url` names in-browser uploads. Run after editing the source:
//   npm run sync-shared
// test/lectureKey.test.ts fails if the copy drifts from the source.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const SOURCE = resolve(here, '../../../supabase/functions/_shared/lectureKey.ts');
export const TARGET = resolve(here, '../src/shared/lectureKey.ts');
export const HEADER =
  '// GENERATED by `npm run sync-shared` from supabase/functions/_shared/lectureKey.ts — DO NOT EDIT.\n' +
  '// Edit the source file, then re-run the sync script (a vitest test enforces the copy matches).\n\n';

export function render(source) {
  return HEADER + source.replace(/\r\n/g, '\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = render(readFileSync(SOURCE, 'utf8'));
  mkdirSync(dirname(TARGET), { recursive: true });
  writeFileSync(TARGET, out);
  console.log(`synced ${TARGET}`);
}
