import { existsSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { lectureKeyCandidate, sanitize, uniqueLectureKey } from '../src/shared/lectureKey.js';

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(here, '../../../supabase/functions/_shared/lectureKey.ts');
const COPY = resolve(here, '../src/shared/lectureKey.ts');
const lf = (s: string) => s.replace(/\r\n/g, '\n');

describe('shared lectureKey copy', () => {
  // The Docker build context is vps/media-worker, so the worker carries a copy.
  // If this fails: run `npm run sync-shared` (never edit the copy by hand).
  it.skipIf(!existsSync(SOURCE))('matches supabase/functions/_shared/lectureKey.ts exactly', () => {
    const copy = lf(readFileSync(COPY, 'utf8'));
    expect(copy.startsWith('// GENERATED by `npm run sync-shared`')).toBe(true);
    expect(copy.endsWith(lf(readFileSync(SOURCE, 'utf8')))).toBe(true);
  });
});

describe('lecture key naming (same as r2-upload-url)', () => {
  const taken = (...keys: string[]) => {
    const set = new Set(keys);
    return async (k: string) => set.has(k);
  };

  it('uses the section title as folder and the lecture title as file name', async () => {
    await expect(uniqueLectureKey('كتاب التوحيد', 'الدرس الأول', 'mp3', taken())).resolves.toBe(
      'lectures/كتاب التوحيد/الدرس الأول.mp3',
    );
  });

  it('appends " (2)" on the first collision, then " (3)"', async () => {
    const base = 'lectures/كتاب التوحيد/الدرس الأول';
    await expect(uniqueLectureKey('كتاب التوحيد', 'الدرس الأول', 'mp3', taken(`${base}.mp3`))).resolves.toBe(
      `${base} (2).mp3`,
    );
    await expect(
      uniqueLectureKey('كتاب التوحيد', 'الدرس الأول', 'mp3', taken(`${base}.mp3`, `${base} (2).mp3`)),
    ).resolves.toBe(`${base} (3).mp3`);
  });

  it('puts unclassified lectures under _unclassified and nameless ones as محاضرة', () => {
    expect(lectureKeyCandidate(null, 'درس', 'mp3')).toBe('lectures/_unclassified/درس.mp3');
    expect(lectureKeyCandidate('قسم', '  ', 'mp3')).toBe('lectures/قسم/محاضرة.mp3');
  });

  it('strips path separators so a title can never escape its folder', () => {
    expect(sanitize('../a/b\\c:d')).toBe('..-a-b-c-d');
    expect(lectureKeyCandidate('x/y', 'a/../b', 'mp3')).toBe('lectures/x-y/a-..-b.mp3');
  });
});
