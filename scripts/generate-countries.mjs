// Writes src/constants/countries.generated.ts. Run after updating the two data packages:
//   node scripts/generate-countries.mjs
// Calling codes and number lengths: libphonenumber-js (Google's libphonenumber metadata).
// Arabic and English names: i18n-iso-countries. Both are dev dependencies, so the
// app ships only the generated table.
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { getCountries, getCountryCallingCode } from 'libphonenumber-js/max';
import { Metadata } from 'libphonenumber-js/core';

const require = createRequire(import.meta.url);
const metadata = require('libphonenumber-js/metadata.max.json');
const iso = require('i18n-iso-countries');
iso.registerLocale(require('i18n-iso-countries/langs/ar.json'));
iso.registerLocale(require('i18n-iso-countries/langs/en.json'));

// The app's own wording for these, and names the dataset lacks.
const AR_OVERRIDES = {
  SD: 'السودان', SA: 'السعودية', AE: 'الإمارات', EG: 'مصر', LY: 'ليبيا', MA: 'المغرب', DZ: 'الجزائر',
  TN: 'تونس', OM: 'عُمان', QA: 'قطر', BH: 'البحرين', KW: 'الكويت', JO: 'الأردن', LB: 'لبنان',
  DE: 'ألمانيا', FR: 'فرنسا', AU: 'أستراليا', US: 'الولايات المتحدة', GB: 'المملكة المتحدة',
  XK: 'كوسوفو', AC: 'جزيرة أسينشين', TA: 'تريستان دا كونا', BQ: 'الجزر الكاريبية الهولندية',
  SS: 'جنوب السودان', PS: 'فلسطين', CD: 'الكونغو الديمقراطية', CG: 'الكونغو', CI: 'ساحل العاج',
  CV: 'الرأس الأخضر', CF: 'أفريقيا الوسطى', TD: 'تشاد', SZ: 'إسواتيني', ZA: 'جنوب أفريقيا',
};
const EN_OVERRIDES = { XK: 'Kosovo', AC: 'Ascension Island', TA: 'Tristan da Cunha' };

// Shown first, in this order: the app's main audience.
const FIRST = ['SD', 'SA', 'AE', 'EG', 'LY', 'MA', 'DZ', 'TN', 'OM', 'QA', 'BH', 'KW', 'JO', 'LB'];
// The country a shared calling code resolves to when only the code is known.
const PRIMARY = { 1: 'US', 7: 'RU', 44: 'GB', 212: 'MA', 61: 'AU', 47: 'NO', 358: 'FI', 262: 'RE', 590: 'GP', 599: 'CW', 290: 'SH' };

const flag = (c) => String.fromCodePoint(...[...c].map((x) => 0x1f1e6 + x.charCodeAt(0) - 65));
const meta = new Metadata(metadata);
const missing = [];
const rows = getCountries().map((c) => {
  const name = AR_OVERRIDES[c] ?? iso.getName(c, 'ar', { select: 'alias' }) ?? iso.getName(c, 'ar');
  if (!name) missing.push(c);
  meta.selectNumberingPlan(c);
  return {
    iso: c,
    code: getCountryCallingCode(c),
    name: name ?? c,
    en: EN_OVERRIDES[c] ?? iso.getName(c, 'en') ?? c,
    flag: flag(c),
    lengths: meta.numberingPlan.possibleLengths(),
  };
});
if (missing.length) throw new Error(`No Arabic name for: ${missing.join(' ')}`);

const collator = new Intl.Collator('ar');
const rank = (r) => {
  const i = FIRST.indexOf(r.iso);
  return i === -1 ? FIRST.length : i;
};
rows.sort((a, b) => rank(a) - rank(b) || collator.compare(a.name, b.name));

const primaries = Object.fromEntries(Object.entries(PRIMARY).map(([k, v]) => [k, v]));
const body = rows.map((r) => `  ${JSON.stringify(r)},`).join('\n');
fs.writeFileSync(
  new URL('../src/constants/countries.generated.ts', import.meta.url),
  `// Generated by scripts/generate-countries.mjs. Do not edit by hand.
import type { Country } from './countries';

export const GENERATED_COUNTRIES: Country[] = [
${body}
];

/** Which country a calling code shared by several resolves to. */
export const PRIMARY_ISO: Record<string, string> = ${JSON.stringify(primaries)};
`,
);
console.log(`${rows.length} countries, ${new Set(rows.map((r) => r.code)).size} calling codes`);
